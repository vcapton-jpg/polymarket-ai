export function getActivePositions(): Position[] {
  return MOCK_POSITIONS
}

export function getResolvedPositions(): Position[] {
  return MOCK_RESOLVED_POSITIONS
}

export function getAllPositions(): Position[] {
  return [...MOCK_POSITIONS, ...MOCK_RESOLVED_POSITIONS]
}

export function getPositionById(id: string): Position | undefined {
  return getAllPositions().find((p) => p.id === id)
}

export function totalCapitalEngaged(): number {
  return MOCK_POSITIONS.reduce((sum, p) => sum + p.stake, 0)
}

/**
 * Total estimated gain across all positions (USD).
 * Renamed from totalEstimatedPnL in V2 — user-facing wording is "gain estimé".
 */
export function totalEstimatedGain(): number {
  return getAllPositions().reduce((sum, p) => sum + p.estimatedGain, 0)
}
